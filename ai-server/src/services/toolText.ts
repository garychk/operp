const interpolate = (template: string, params?: Record<string, string | number>): string => {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    params[key] === undefined || params[key] === null ? match : String(params[key]),
  );
};

export interface ToolText {
  (key: ToolTextKey, params?: Record<string, string | number>): string;
  /** 归一后的语言，供少数需要自己分支的场景使用 */
  locale: UiLocale;
}

/** 生成某个界面语言的文案函数 */
export const toolText = (locale?: string): ToolText => {
  const target = normalizeUiLocale(locale);
  const tt = ((key: ToolTextKey, params?: Record<string, string | number>) =>
    interpolate(DICT[key][target], params)) as ToolText;
  tt.locale = target;
  return tt;
};

